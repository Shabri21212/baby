    public const PASS_PERCENT = 80;

    /** @var array<int, bool> */
    private static array $stepCache = [];

    public static function isChapter(?array $chapter): bool
    {
        return $chapter !== null && mb_stripos(trim((string) ($chapter['title'] ?? '')), 'Экватор') === 0;
    }

    /** Шаг относится к главе «Экватор»? */
    public static function isStep(int $stepId): bool
    {
        if (!isset(self::$stepCache[$stepId])) {
            $row = Db::one('SELECT c.title FROM course_steps s JOIN course_chapters c ON c.id = s."chapterId" WHERE s.id = ?', [$stepId]);
            self::$stepCache[$stepId] = $row !== null && self::isChapter(['title' => (string) $row['title']]);
        }
        return self::$stepCache[$stepId];
    }

    /** @return array{attempts: int, bestPercent: int, lastPercent: int, passed: bool, passedAt: ?string, stats: array}|null */
    public static function result(string $userId, int $stepId): ?array
    {
        $r = Db::one('SELECT * FROM course_quiz_results WHERE "userId" = ? AND "stepId" = ?', [$userId, $stepId]);
        if ($r === null) {
            return null;
        }
        $stats = json_decode((string) ($r['statsJson'] ?? ''), true);
        return [
            'attempts' => (int) $r['attempts'],
            'bestPercent' => (int) $r['bestPercent'],
            'lastPercent' => (int) $r['lastPercent'],
            'passed' => boolish($r['passed']),
            'passedAt' => $r['passedAt'] !== null ? (string) $r['passedAt'] : null,
            'stats' => is_array($stats) ? $stats : [],
        ];
    }

    public static function passed(string $userId, int $stepId): bool
    {
        return (bool) (self::result($userId, $stepId)['passed'] ?? false);
    }

    public static function resetFor(string $userId): void
    {
        Db::exec('DELETE FROM course_quiz_results WHERE "userId" = ?', [$userId]);
    }

    /**
     * Пересчитывает попытку по журналу нажатий.
     * $logs[i] — индексы, нажатые в задании i: для выбора — индексы вариантов,
     * для последовательности — индексы шагов в правильном порядке.
     *
     * @param list<mixed> $logs
     * @return array{ok: bool, total: int, firstTry: int, mistakes: int, percent: int, passed: bool, missed: list<int>}
     */
    public static function evaluate(array $logs): array
    {
        $tasks = self::tasks();
        $firstTry = 0;
        $mistakes = 0;
        $missed = [];
        $ok = count($logs) === count($tasks);
        foreach ($tasks as $i => $task) {
            $log = $logs[$i] ?? null;
            if (!is_array($log) || count($log) > 50) {
                $ok = false;
                break;
            }
            $log = array_values(array_map('intval', $log));
            if ($task['type'] === 'choice') {
                $correct = (int) $task['correct'];
                $last = $log ? $log[count($log) - 1] : -1;
                if ($last !== $correct || count(array_unique($log)) !== count($log) || $last >= count($task['options'])) {
                    $ok = false;
                    break;
                }
                $wrong = count($log) - 1;
            } else {
                $pos = 0;
                $wrong = 0;
                $n = count($task['steps']);
                foreach ($log as $idx) {
                    if ($idx === $pos) {
                        $pos++;
                    } elseif ($idx > $pos && $idx < $n) {
                        $wrong++;
                    } else {
                        $ok = false;
                        break 2;
                    }
                }
                if ($pos !== $n) {
                    $ok = false;
                    break;
                }
            }
            $mistakes += $wrong;
            if ($wrong === 0) {
                $firstTry++;
            } else {
                $missed[] = $i;
            }
        }
        $total = count($tasks);
        $percent = $total > 0 ? (int) floor($firstTry / $total * 100) : 0;
        return [
            'ok' => $ok,
            'total' => $total,
            'firstTry' => $firstTry,
            'mistakes' => $mistakes,
            'percent' => $percent,
            'passed' => $ok && $percent >= self::PASS_PERCENT,
            'missed' => $missed,
        ];
    }

    /** Сохраняет попытку. Зачтённую проверку не перезаписывает. */
    public static function saveAttempt(string $userId, int $stepId, array $eval): array
    {
        $now = now_iso();
        $prev = self::result($userId, $stepId);
        $stats = ['firstTry' => $eval['firstTry'], 'mistakes' => $eval['mistakes'], 'total' => $eval['total'], 'missed' => $eval['missed']];
        if ($prev === null) {
            Db::insert('course_quiz_results', [
                'userId' => $userId, 'stepId' => $stepId, 'attempts' => 1,
                'bestPercent' => $eval['percent'], 'lastPercent' => $eval['percent'],
                'passed' => $eval['passed'] ? 1 : 0, 'passedAt' => $eval['passed'] ? $now : null,
                'statsJson' => json_encode($stats, JSON_UNESCAPED_UNICODE), 'updatedAt' => $now,
            ]);
        } elseif (!$prev['passed']) {
            Db::exec(
                'UPDATE course_quiz_results SET attempts = attempts + 1, "bestPercent" = ?, "lastPercent" = ?, passed = ?, "passedAt" = ?, "statsJson" = ?, "updatedAt" = ? WHERE "userId" = ? AND "stepId" = ?',
                [max($prev['bestPercent'], $eval['percent']), $eval['percent'], $eval['passed'] ? 1 : 0, $eval['passed'] ? $now : null, json_encode($stats, JSON_UNESCAPED_UNICODE), $now, $userId, $stepId],
            );
        }
        return self::result($userId, $stepId) ?? [];
    }

