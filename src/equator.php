/**
 * «Экватор. Проверка знаний на практике» — промежуточная проверка по Админ ПО.
 *
 * Глава курса, название которой начинается с «Экватор», показывается не как статья, а как
 * интерактивная проверка из 17 заданий (выбор действия + сборка последовательности).
 * Считается результат с ПЕРВОЙ попытки: пока он ниже PASS_PERCENT, шаг не завершается
 * и следующие модули курса закрыты — проверку проходят заново. После зачёта
 * результат фиксируется, и пройти проверку повторно уже нельзя.
 *
 * Сервер сам пересчитывает результат по журналу нажатий — клиенту не верим на слово.
 */
final class Equator
